# Take 2 different number as input and calculate sum, subtraction, product and division.


num_1 = int(input("Enter number 1: "));
num_2 = int(input("Enter number 2: "));

sum = num_1 + num_2;
diff = num_2 - num_1;
product = num_1 * num_2;
divison = num_2 / num_1;

print("Sum = ", sum);
print("Diff = ", diff);
print("Product = ", product);
print("Division = ", divison);